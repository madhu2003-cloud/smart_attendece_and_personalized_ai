"""Generate the demo attendance dataset for model development.

IMPORTANT - what this is and is not:

The project spec (Module 6) says: if a public dataset does not contain the
required attendance features, do NOT invent real-world claims. Instead create a
clearly documented synthetic/demo dataset for development, and later replace or
supplement it with attendance records generated by the actual system.

This script does exactly that. It produces:

  1. data/attendance_dataset.csv
     A deterministic (random_state=42) synthetic dataset of 600 students with
     the attendance/academic features listed in the spec. The target
     `attendance_risk` is computed from a documented rule, plus label noise:

         risk = 1 if (attendance_percentage < 70
                      or consecutive_absences >= 5
                      or attendance_last_7_days < 50)
                0 otherwise
         then ~3% of labels are flipped at random.

     Every row is clearly synthetic (names like "Student 101"). Nothing here
     claims to be real student data.

  2. Attendance records for students registered in the SQLite database
     (source='sample'), so the Attendance module and the Pandas pipeline have
     data to work with during the demo.

Run:  python generate_demo_data.py
"""

import os
import random
import sqlite3
import datetime

import numpy as np
import pandas as pd

from database import get_db

BASE_DIR = os.path.dirname(__file__)
DATA_DIR = os.path.join(BASE_DIR, 'data')
CSV_PATH = os.path.join(DATA_DIR, 'attendance_dataset.csv')

DEPARTMENTS = ['CSE', 'ECE', 'IT', 'MECH', 'CIVIL', 'EEE']
YEARS = ['1st', '2nd', '3rd', '4th']
SECTIONS = ['A', 'B', 'C']
N_STUDENTS = 600
RANDOM_STATE = 42


def generate_dataset_csv():
    """Create the synthetic CSV deterministically."""
    os.makedirs(DATA_DIR, exist_ok=True)
    rng = np.random.default_rng(RANDOM_STATE)

    rows = []
    for i in range(N_STUDENTS):
        roll = 101 + i
        dept = DEPARTMENTS[rng.integers(0, len(DEPARTMENTS))]
        year = YEARS[rng.integers(0, len(YEARS))]
        section = SECTIONS[rng.integers(0, len(SECTIONS))]

        total_classes = int(rng.integers(30, 46))

        # Underlying attendance propensity (most students 60-95%).
        prop = rng.normal(0.78, 0.13)
        prop = float(np.clip(prop, 0.35, 0.98))

        # Consecutive absences: most students have short streaks; long streaks
        # are more common for low-propensity students.
        consecutive_absences = int(rng.geometric(0.35))
        consecutive_absences = min(consecutive_absences, 14)

        # Recent windows are correlated with overall propensity but noisier.
        last7 = float(np.clip(prop + rng.normal(0.0, 0.08), 0.0, 1.0))
        last30 = float(np.clip(prop + rng.normal(0.0, 0.05), 0.0, 1.0))

        # Daily attendance is sampled around the propensity; the recent windows
        # and the overall percentage stay consistent.
        attended_days = sum(
            1 for _ in range(total_classes)
            if rng.random() < prop
        )
        attendance_percentage = round(100.0 * attended_days / total_classes, 1)

        # Slight negative drift between attendance and lateness.
        late_arrivals = max(0, int(rng.normal((1 - prop) * 14, 2.5)))

        # Academic features are correlated with attendance, not causally tied
        # to it - correlation is not causation, and the README says so.
        assignment_score = float(np.clip(38 + 0.5 * attendance_percentage + rng.normal(0, 8), 0, 100))
        internal_marks = float(np.clip(35 + 0.55 * attendance_percentage + rng.normal(0, 7), 0, 100))
        previous_semester_percentage = float(np.clip(42 + 0.45 * attendance_percentage + rng.normal(0, 8), 0, 100))
        study_hours = float(np.clip(rng.normal(3.0 + 0.03 * attendance_percentage, 1.2), 0, 8))

        # Documented rule for the target (see module docstring). The risk
        # label comes from a latent score over attendance, streaks and recent
        # attendance plus noise - so it is learnable by the models but not a
        # perfectly crisp threshold on any single feature.
        penalty = max(0.0, 72.0 - attendance_percentage) * 2.0
        penalty += consecutive_absences * 1.2
        penalty += max(0.0, 45.0 - last7 * 100.0) * 0.8
        risk = 1 if penalty + rng.normal(0.0, 6.0) > 12.0 else 0

        rows.append({
            'roll_number': str(roll),
            'name': f'Student {roll}',
            'department': dept,
            'year': year,
            'section': section,
            'total_classes': total_classes,
            'classes_attended': attended_days,
            'classes_absent': total_classes - attended_days,
            'attendance_percentage': attendance_percentage,
            'absence_percentage': round(100.0 - attendance_percentage, 1),
            'consecutive_absences': consecutive_absences,
            'attendance_last_7_days': round(last7 * 100.0, 1),
            'attendance_last_30_days': round(last30 * 100.0, 1),
            'assignment_score': round(assignment_score, 1),
            'internal_marks': round(internal_marks, 1),
            'study_hours': round(study_hours, 1),
            'previous_semester_percentage': round(previous_semester_percentage, 1),
            'number_of_late_arrivals': late_arrivals,
            'attendance_risk': risk,
        })

    df = pd.DataFrame(rows)

    # Add ~3% label noise so the classes are not perfectly separable.
    flip_idx = rng.choice(df.index, size=int(len(df) * 0.03), replace=False)
    df.loc[flip_idx, 'attendance_risk'] = 1 - df.loc[flip_idx, 'attendance_risk']

    df.to_csv(CSV_PATH, index=False)
    print(f"Wrote {len(df)} synthetic student rows -> {CSV_PATH}")
    print("Risk distribution:\n", df['attendance_risk'].value_counts().to_string())
    return df


def seed_attendance_records(days=30, base_date=None):
    """Insert sample attendance rows for students registered in the DB.

    Used to give the Attendance module and the Pandas pipeline demo data.
    Every row is marked with source='sample' so real records (source='manual')
    can be distinguished later. Does not overwrite existing rows.
    """
    conn = get_db()
    cur = conn.cursor()
    students = cur.execute("SELECT roll_number FROM students").fetchall()

    if not students:
        conn.close()
        return 0

    rng = np.random.default_rng(RANDOM_STATE)
    today = (datetime.date.fromisoformat(base_date)
             if base_date else datetime.date.today())
    class_dates = []
    d = today - datetime.timedelta(days=days * 2)
    while len(class_dates) < days:
        if d.weekday() < 5:  # weekdays only
            class_dates.append(d.isoformat())
        d += datetime.timedelta(days=1)

    inserted = 0
    for student in students:
        roll = student['roll_number']
        prop = float(np.clip(rng.normal(0.82, 0.11), 0.40, 0.98))
        for date_str in class_dates:
            if rng.random() < prop:
                hour = rng.integers(8, 10)
                minute = rng.integers(0, 60)
                time_str = f"{hour:02d}:{minute:02d}:00"
                try:
                    cur.execute("""
                        INSERT OR IGNORE INTO attendance (roll_number, date, time, status, source)
                        VALUES (?, ?, ?, 'Present', 'sample')
                    """, (roll, date_str, time_str))
                    inserted += cur.rowcount if cur.rowcount > 0 else 0
                except sqlite3.IntegrityError:
                    continue
    conn.commit()
    conn.close()
    print(f"Seeded {inserted} sample attendance records for {len(students)} students.")
    return inserted


if __name__ == '__main__':
    generate_dataset_csv()
    seed_attendance_records()
